/**
 * GreenChainz — Persona-Aware Copy Generator
 *
 * Generates tailored outreach emails, platform onboarding copy, RFQ
 * invitation messages, and supplier pitch copy — all driven by the
 * detected persona's financial lever, not generic green messaging.
 *
 * Principle: "Stop selling the planet. Sell the solution."
 *
 * Uses Azure OpenAI (gpt-4.1-mini) via the existing llm.ts client.
 */

import { type PersonaDetectionResult } from "./persona-detector";

// ---------------------------------------------------------------------------
// Copy Request Types
// ---------------------------------------------------------------------------

export type CopyType =
  | "cold_outreach_email"      // First cold email to a new contact
  | "followup_email"           // Follow-up after no response
  | "rfq_invitation"           // Invite a buyer to submit an RFQ
  | "supplier_pitch"           // Pitch a supplier to join the platform
  | "platform_welcome"         // In-app welcome message after signup
  | "rfq_match_notification"   // Notify a buyer of a matched supplier
  | "bid_received_notification"; // Notify a buyer that a bid came in

export interface CopyRequest {
  copyType: CopyType;
  persona: PersonaDetectionResult;
  /** Recipient's first name */
  recipientName?: string;
  /** Recipient's company name */
  recipientCompany?: string;
  /** Specific material or product category relevant to this contact */
  materialCategory?: string;
  /** Any specific project context (e.g., "LEED Gold office tower in NYC") */
  projectContext?: string;
  /** Sender name (defaults to "Jerit" for cold outreach) */
  senderName?: string;
  /** Whether to include a CTA link */
  includeCta?: boolean;
  /** Override tone: "direct" (default) | "formal" | "casual" */
  tone?: "direct" | "formal" | "casual";
}

export interface GeneratedCopy {
  subject?: string;       // For email types
  body: string;
  ctaText?: string;
  ctaUrl?: string;
  personaUsed: string;
  driverUsed: string;
  /** Confidence of the underlying persona detection */
  confidence: number;
  /** Whether this was auto-generated without human review */
  autoGenerated: boolean;
}

// ---------------------------------------------------------------------------
// Prompt Builder
// ---------------------------------------------------------------------------

function buildSystemPrompt(): string {
  return `You are the outreach and copy engine for GreenChainz — the B2B marketplace for verified sustainable building materials.

CORE PRINCIPLE: Decision-makers do NOT buy green to save the planet. They buy green because the alternative is a quantifiable financial liability. You NEVER lead with sustainability, eco-friendliness, or saving the environment. You ALWAYS lead with the specific financial driver for the persona you are addressing.

GREENCHAINZ DIFFERENTIATORS (use these, not generic claims):
- 1,500+ verified materials with EPD data
- AI Audit Agent for supplier verification
- Material Credit Score (proprietary sustainability scoring)
- SWAP Engine (suggests greener alternatives with performance data)
- Revit plugin (live in architect workflows)
- EC3 and EPD International data integrations
- Partners: Building Transparency, EPD International, Autodesk, Microsoft

WRITING RULES:
1. Lead with the financial/operational pain — not the product
2. Use the persona's exact resonant language — never their avoid language
3. Be specific: cite numbers, regulations, and real consequences
4. Keep cold emails under 120 words in the body
5. One clear CTA per email — never two
6. No filler phrases: "I hope this finds you well", "I wanted to reach out", "game-changer", "revolutionary"
7. No green washing language: "sustainable future", "save the planet", "eco-friendly", "green"
8. Subject lines: max 8 words, no clickbait, no question marks
9. Sign off as the persona's peer, not a vendor pitching them`;
}

function buildUserPrompt(req: CopyRequest): string {
  const {
    copyType,
    persona,
    recipientName,
    recipientCompany,
    materialCategory,
    projectContext,
    senderName = "Jerit",
    tone = "direct",
  } = req;

  const recipientStr = recipientName
    ? `${recipientName}${recipientCompany ? ` at ${recipientCompany}` : ""}`
    : recipientCompany ?? "the recipient";

  const materialStr = materialCategory
    ? `The relevant material category is: ${materialCategory}.`
    : "";

  const projectStr = projectContext
    ? `Project context: ${projectContext}.`
    : "";

  const toneInstructions: Record<string, string> = {
    direct: "Be direct and concise. No pleasantries. Get to the point in the first sentence.",
    formal: "Be professional and formal. Appropriate for C-suite and institutional buyers.",
    casual: "Be conversational but still data-driven. Appropriate for subcontractors and field roles.",
  };

  const copyTypeInstructions: Record<CopyType, string> = {
    cold_outreach_email: `Write a cold outreach email. Subject line + body. Under 120 words in the body. End with a single low-friction CTA (e.g., "Worth a 15-minute call this week?").`,
    followup_email: `Write a follow-up email to someone who didn't respond to the first outreach. Reference that this is a follow-up. Under 80 words. Different angle from the first email — lead with a specific data point or regulatory deadline.`,
    rfq_invitation: `Write an in-platform message inviting this buyer to submit an RFQ. Under 60 words. Tone: peer-to-peer. Make it feel like a warm introduction to a matched supplier, not a marketing message.`,
    supplier_pitch: `Write an outreach email to a supplier asking them to join GreenChainz as a verified supplier. Lead with the buyer demand signal for their product category. Under 120 words.`,
    platform_welcome: `Write an in-app welcome message shown after signup. Under 80 words. Make it immediately useful — tell them exactly what to do first based on their role.`,
    rfq_match_notification: `Write a short in-app notification (under 40 words) telling a buyer that GreenChainz found a verified supplier match for their RFQ. Lead with the match quality signal relevant to their persona.`,
    bid_received_notification: `Write a short in-app notification (under 40 words) telling a buyer that a bid has been received on their RFQ. Lead with the data point most relevant to their financial driver.`,
  };

  return `RECIPIENT: ${recipientStr}
PERSONA: ${persona.subPersonaTitle} (${persona.layerName})
FINANCIAL DRIVER: ${persona.driver}
CORE PAIN: ${persona.pain}
GREENCHAINZ SOLUTION: ${persona.keySolution}
RESONANT LANGUAGE TO USE: ${persona.resonantLanguage.slice(0, 5).join(", ")}
LANGUAGE TO AVOID: ${persona.avoidLanguage.join(", ")}
${materialStr}
${projectStr}
SENDER: ${senderName}, Founder — GreenChainz
TONE: ${toneInstructions[tone]}

TASK: ${copyTypeInstructions[copyType]}

${copyType.includes("email") ? "Return JSON with fields: subject (string), body (string), ctaText (string)." : "Return JSON with field: body (string)."}
Return ONLY valid JSON. No markdown, no explanation.`;
}

// ---------------------------------------------------------------------------
// LLM Call
// ---------------------------------------------------------------------------

async function callLLM(systemPrompt: string, userPrompt: string): Promise<string> {
  const { invokeLLM } = await import("../_core/llm");
  const result = await invokeLLM({
    messages: [
      { role: "system" as const, content: systemPrompt },
      { role: "user" as const, content: userPrompt },
    ],
  });
  const message = result.choices[0]?.message?.content;
  return typeof message === "string" ? message : JSON.stringify(message ?? "");
}

// ---------------------------------------------------------------------------
// Main Generator
// ---------------------------------------------------------------------------

export async function generatePersonaCopy(
  req: CopyRequest
): Promise<GeneratedCopy> {
  const systemPrompt = buildSystemPrompt();
  const userPrompt = buildUserPrompt(req);

  let rawResponse: string;
  try {
    rawResponse = await callLLM(systemPrompt, userPrompt);
  } catch (err) {
    throw new Error(`LLM call failed for persona copy generation: ${err}`, { cause: err });
  }

  // Parse JSON response
  let parsed: { subject?: string; body: string; ctaText?: string };
  try {
    // Strip any accidental markdown code fences
    const cleaned = rawResponse.replace(/^```json\s*/i, "").replace(/```\s*$/i, "").trim();
    parsed = JSON.parse(cleaned);
  } catch {
    // Fallback: treat entire response as body
    parsed = { body: rawResponse };
  }

  const isEmailType = req.copyType.includes("email");

  return {
    subject: isEmailType ? parsed.subject : undefined,
    body: parsed.body,
    ctaText: parsed.ctaText,
    ctaUrl: req.includeCta ? "https://greenchainz.com/signup" : undefined,
    personaUsed: req.persona.subPersonaTitle,
    driverUsed: req.persona.driver,
    confidence: req.persona.confidence,
    autoGenerated: req.persona.autoApproved,
  };
}

// ---------------------------------------------------------------------------
// Batch Generator — for processing a list of classified contacts
// ---------------------------------------------------------------------------

export interface BatchCopyRequest {
  contacts: Array<{
    externalId?: string;
    name?: string;
    email?: string;
    company?: string;
    persona: PersonaDetectionResult;
    materialCategory?: string;
  }>;
  copyType: CopyType;
  senderName?: string;
  includeCta?: boolean;
}

export interface BatchCopyOutput {
  externalId?: string;
  name?: string;
  email?: string;
  company?: string;
  copy: GeneratedCopy;
  generatedAt: string;
  error?: string;
}

export async function generatePersonaCopyBatch(
  req: BatchCopyRequest
): Promise<BatchCopyOutput[]> {
  const results: BatchCopyOutput[] = [];

  for (const contact of req.contacts) {
    try {
      const copy = await generatePersonaCopy({
        copyType: req.copyType,
        persona: contact.persona,
        recipientName: contact.name,
        recipientCompany: contact.company,
        materialCategory: contact.materialCategory,
        senderName: req.senderName,
        includeCta: req.includeCta,
      });

      results.push({
        externalId: contact.externalId,
        name: contact.name,
        email: contact.email,
        company: contact.company,
        copy,
        generatedAt: new Date().toISOString(),
      });
    } catch (err) {
      results.push({
        externalId: contact.externalId,
        name: contact.name,
        email: contact.email,
        company: contact.company,
        copy: {
          body: "",
          personaUsed: contact.persona.subPersonaTitle,
          driverUsed: contact.persona.driver,
          confidence: contact.persona.confidence,
          autoGenerated: false,
        },
        generatedAt: new Date().toISOString(),
        error: String(err),
      });
    }
  }

  return results;
}
