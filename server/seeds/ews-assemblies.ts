// ─── Seed function ────────────────────────────────────────────────────────────

async function seed() {
  console.log("🌱  Seeding EWS assemblies…");

  for (const assembly of ASSEMBLIES) {
    // Derive totalGwpPerSf from first framing option (null + opt-1 components)
    const opt1Total = assembly.components.reduce((sum, c) => {
      if (c.framingOption === null || c.framingOption === 1) {
        return sum + (parseFloat(c.carbonPer1000sf) || 0);
      }
      return sum;
    }, 0);

    const [inserted] = await db
      .insert(assemblySpecs)
      .values({
        name: assembly.name,
        category: assembly.category,
        description: assembly.description,
        carbonTier: assembly.carbonTier,
        assemblyTypeTags: assembly.assemblyTypeTags,
        framingTypeTags: assembly.framingTypeTags,
        exteriorFinishTags: assembly.exteriorFinishTags,
        gwpPer1000sf: String(Math.round(opt1Total)),
        updatedAt: new Date(),
      })
      .returning({ id: assemblySpecs.id });

    const specId = inserted.id;

    for (const c of assembly.components) {
      await db.insert(ewsComponents).values({
        assemblySpecId: specId,
        zone: c.zone,
        layerOrder: c.layerOrder,
        layerName: c.layerName,
        framingOption: c.framingOption,
        manufacturer: c.manufacturer,
        productName: c.productName,
        epdNumber: c.epdNumber,
        dimensionParam: c.dimensionParam,
        gwpValue: c.gwpValue,
        gwpUnits: c.gwpUnits,
        declaredUnit: c.declaredUnit,
        msfFactor: c.msfFactor,
        carbonPer1000sf: c.carbonPer1000sf,
        notes: c.notes,
      });
    }

    console.log(`  ✓  ${assembly.name}  (${assembly.components.length} components)`);
  }

  console.log(`\n✅  Done — seeded ${ASSEMBLIES.length} assemblies.`);
  process.exit(0);
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
