async function seed() {
  console.log('[Seed] Starting EWS carbon component seed...\n');

  for (const [assemblyName, components] of Object.entries(EWS_COMPONENTS)) {
    // Look up the parent assembly by name
    const [parent] = await db
      .select({ id: materialAssemblySpecs.id })
      .from(materialAssemblySpecs)
      .where(eq(materialAssemblySpecs.name, assemblyName))
      .limit(1);

    if (!parent) {
      console.warn(`[Seed] ⚠️ Assembly "${assemblyName}" not found — skipping`);
      continue;
    }

    // Delete existing components for this assembly (idempotent re-run)
    await db.delete(ewsCarbonComponents)
      .where(eq(ewsCarbonComponents.assemblySpecId, parent.id));

    // Insert all components
    await db.insert(ewsCarbonComponents).values(
      components.map((c) => ({
        assemblySpecId: parent.id,
        zone: c.zone,
        layerOrder: c.layerOrder,
        layerName: c.layerName,
        framingOption: c.framingOption,
        manufacturer: c.manufacturer,
        productName: c.productName,
        epdNumber: c.epdNumber,
        dimensionParam: c.dimensionParam,
        gwpValue: String(c.gwpValue),
        gwpUnits: c.gwpUnits,
        declaredUnit: c.declaredUnit,
        msfFactor: String(c.msfFactor),
        carbonPer1000sf: String(c.carbonPer1000sf),
        notes: c.notes,
      }))
    );

    console.log(`[Seed] ✅ ${assemblyName}: ${components.length} components`);
  }

  console.log('\n[Seed] Done.');
}

seed()
  .catch((err) => { console.error('[Seed] FAILED:', err); process.exit(1); })
  .finally(() => pool.end());
