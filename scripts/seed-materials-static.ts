// ── Runner ─────────────────────────────────────────────────────────────────────

async function main() {
  const db = await getDb();
  if (!db) {
    console.error("Could not connect to database.");
    process.exit(1);
  }

  // Check for existing seed rows
  const existing = await db
    .select({ count: sql<number>`count(*)::int` })
    .from(materials)
    .where(eq(materials.dataSource, "static-seed"));
  const existingCount = existing[0]?.count ?? 0;

  if (existingCount > 0 && !force) {
    console.log(
      `Skipping — ${existingCount} static-seed rows already exist. Run with --force to wipe and re-seed.`
    );
    process.exit(0);
  }

  if (force && existingCount > 0) {
    console.log(`--force: deleting ${existingCount} existing static-seed rows…`);
    await db.delete(materials).where(eq(materials.dataSource, "static-seed"));
    console.log("Deleted.");
  }

  console.log(`Seeding ${SEED_MATERIALS.length} materials…\n`);

  let inserted = 0;
  let errors = 0;

  for (const mat of SEED_MATERIALS) {
    try {
      await db.insert(materials).values(mat as any);
      console.log(`  ✓ ${mat.name}`);
      inserted++;
    } catch (err) {
      console.error(`  ✗ ${mat.name}: ${String(err)}`);
      errors++;
    }
  }

  console.log(`\nDone. ${inserted} inserted, ${errors} errors.`);
  process.exit(errors > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error("Fatal:", err);
  process.exit(1);
});
